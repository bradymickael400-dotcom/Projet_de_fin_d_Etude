CREATE TABLE IF NOT EXISTS brady.regulatory_sources (
    id BIGSERIAL PRIMARY KEY,
    source_key VARCHAR(100) NOT NULL UNIQUE,
    title TEXT NOT NULL,
    source_type VARCHAR(40) NOT NULL,
    authority VARCHAR(160) NOT NULL,
    jurisdiction VARCHAR(100) NOT NULL,
    transport_modes TEXT[] NOT NULL DEFAULT '{}',
    official_url TEXT,
    adoption_date DATE,
    effective_date DATE,
    legal_status VARCHAR(40) NOT NULL DEFAULT 'TO_VERIFY',
    applicability_conditions TEXT NOT NULL DEFAULT '',
    summary TEXT NOT NULL DEFAULT '',
    verified_at DATE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS brady.decision_history (
    id BIGSERIAL PRIMARY KEY,
    history_uid UUID NOT NULL UNIQUE,
    trace_id UUID,
    black_box_id INTEGER,
    container_id VARCHAR(100),
    subject_type VARCHAR(40) NOT NULL,
    subject_id VARCHAR(120),
    event_type VARCHAR(80) NOT NULL,
    actor_role VARCHAR(40),
    actor_id VARCHAR(80),
    action TEXT NOT NULL,
    reaction TEXT NOT NULL DEFAULT '',
    ai_remarks JSONB NOT NULL DEFAULT '{}'::jsonb,
    source_keys JSONB NOT NULL DEFAULT '[]'::jsonb,
    applicability_status VARCHAR(40) NOT NULL DEFAULT 'NOT_ASSESSED',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS ix_decision_history_box_created
ON brady.decision_history(black_box_id, created_at DESC);
CREATE INDEX IF NOT EXISTS ix_decision_history_container_created
ON brady.decision_history(container_id, created_at DESC);
CREATE INDEX IF NOT EXISTS ix_decision_history_trace
ON brady.decision_history(trace_id);

